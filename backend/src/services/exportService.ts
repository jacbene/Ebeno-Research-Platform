// ============================================================
// ✅ Helper : nom de fichier sûr et unique
// ============================================================
const safeName = (name: string, fallback: string = 'document', maxLen: number = 80): string => {
  const clean = (name || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')       // retire les accents
    .replace(/[^a-zA-Z0-9._-]/g, '_')      // remplace tout caractère spécial
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .substring(0, maxLen);
  return clean || fallback;
};

// ============================================================
// ✅ Helper : télécharge un fichier Cloudinary
// ============================================================
const downloadCloudinaryFile = async (url: string): Promise<Buffer | null> => {
  try {
    const response = await fetch(url);
    if (!response.ok) {
      logger.warn(`⚠️ [export] Cloudinary download échoué (${response.status}): ${url}`);
      return null;
    }
    const arrayBuffer = await response.arrayBuffer();
    return Buffer.from(arrayBuffer);
  } catch (err: any) {
    logger.warn(`⚠️ [export] Erreur téléchargement Cloudinary: ${err.message}`);
    return null;
  }
};

// ============================================================
// ✅ Helper : lire un fichier local ou télécharger Cloudinary
// ============================================================
const readFileContent = async (filePath: string): Promise<Buffer | null> => {
  if (!filePath) return null;

  // Cas 1 : URL Cloudinary
  if (filePath.startsWith('http://') || filePath.startsWith('https://')) {
    return downloadCloudinaryFile(filePath);
  }

  // Cas 2 : Chemin local (uploads/projects/xxx)
  const localPath = path.isAbsolute(filePath)
    ? filePath
    : path.join(__dirname, '../../', filePath);

  if (existsSync(localPath)) {
    try {
      return readFileSync(localPath);
    } catch (err: any) {
      logger.warn(`⚠️ [export] Lecture locale échouée: ${err.message}`);
    }
  }

  return null;
};

