// ✅ FONCTION PRINCIPALE
// ============================================================
export const exportProject = async (
  projectId: string,
  userId: string,
  auditContext?: ExportAuditContext
): Promise<Buffer> => {
  // 1. Vérifier l'autorisation
  const member = await db('project_members').where({ projectId, userId }).first();
  if (!member) throw new Error('Non autorisé');

  // 2. Récupérer le projet
  const project = await db('projects').where({ id: projectId }).first();
  if (!project) throw new Error('Projet non trouvé');

  // 3. Récupérer la langue du user
  const user = await db('users').where({ id: userId }).first();
  const lang = normalizeLang(user?.language);
  const S = README_STRINGS[lang];

  // 4. Récupérer toutes les données en parallèle
  const [
    transcriptions,
    memos,
    files,
    collabDocs,
    entities,
    summaries,
    comments,
  ] = await Promise.all([
    db('transcriptions').where({ projectId }).orderBy('createdAt', 'desc'),
    db('memos').where({ projectId }).orderBy('createdAt', 'desc'),
    db('project_files').where({ projectId }).orderBy('uploadedAt', 'desc'),
    db('collaboration_documents').where({ projectId }).orderBy('updatedAt', 'desc'),
    db('document_entities').whereIn(
      'documentId',
      db('transcriptions').where({ projectId }).select('id').union(
        db('memos').where({ projectId }).select('id').union(
          db('collaboration_documents').where({ projectId }).select('id')
        )
      )
    ).catch(() => []),
    db('document_summaries').whereIn(
      'documentId',
      db('transcriptions').where({ projectId }).select('id').union(
        db('memos').where({ projectId }).select('id').union(
          db('collaboration_documents').where({ projectId }).select('id')
        )
      )
    ).catch(() => []),
    db('comments')
      .whereIn(
        'documentId',
        db('transcriptions').where({ projectId }).select('id').union(
          db('memos').where({ projectId }).select('id').union(
            db('collaboration_documents').where({ projectId }).select('id')
          )
        )
      )
      .whereNull('deletedAt')
      .catch(() => []),
  ]);

  // 5. Créer le ZIP
  const zip = new AdmZip();
  const projectFolder = `projet_${safeName(project.title, 'projet')}`;

  // 5.1 Métadonnées
  const metadata = {
    project: {
      id: project.id,
      title: project.title,
      description: project.description,
      status: project.status,
      visibility: project.visibility,
      createdAt: project.createdAt,
      updatedAt: project.updatedAt,
    },
    exported_at: new Date().toISOString(),
    exported_by: user?.email || null,
    language: lang,
    stats: {
      transcriptions: transcriptions.length,
      memos: memos.length,
      collaborativeDocuments: collabDocs.length,
      files: files.length,
      entities: entities.length,
      summaries: summaries.length,
      comments: comments.length,
    },
  };
  zip.addFile(
    `${projectFolder}/metadata.json`,
    Buffer.from(JSON.stringify(metadata, null, 2), 'utf-8')
  );

  // 5.2 README (i18n)
  const statsLines = [
    `- ${S.transcriptions} : ${transcriptions.length}`,
    `- ${S.memos} : ${memos.length}`,
    `- ${S.collaborativeDocs} : ${collabDocs.length}`,
    `- ${S.files} : ${files.length}`,
    `- ${S.entities} : ${entities.length}`,
    `- ${S.summaries} : ${summaries.length}`,
    `- ${S.comments} : ${comments.length}`,
  ].join('\n');

  const readmeContent = `# ${S.title} : ${project.title}

## 📋 ${S.description}
${project.description || S.noDescription}

## 📊 ${S.statistics}
${statsLines}

## 📅 ${S.exportedOn}
${new Date().toISOString()}

---
${S.generatedBy}
`;

  zip.addFile(`${projectFolder}/README.md`, Buffer.from(readmeContent, 'utf-8'));

  // 5.3 Transcriptions
  if (transcriptions.length > 0) {
    transcriptions.forEach((t: any, idx: number) => {
      const suffix = idx > 0 ? `_${idx}` : '';
      const fileName = `${safeName(t.title, 'sans_titre')}${suffix}.txt`;
      const content = `${S.title}: ${t.title}
Status: ${t.status}
Language: ${t.language || 'inconnue'}
Date: ${t.createdAt}

---

${t.transcriptText || '(Aucun texte)'}`;
      zip.addFile(`${projectFolder}/transcriptions/${fileName}`, Buffer.from(content, 'utf-8'));
    });
  }

  // 5.4 Mémos
  if (memos.length > 0) {
    memos.forEach((m: any, idx: number) => {
      const suffix = idx > 0 ? `_${idx}` : '';
      const fileName = `${safeName(m.title, 'sans_titre')}${suffix}.txt`;
      const content = `${m.title}
Date: ${m.createdAt}
Language: ${m.language || 'inconnue'}

---

${m.content || '(Vide)'}`;
      zip.addFile(`${projectFolder}/memos/${fileName}`, Buffer.from(content, 'utf-8'));
    });
  }

  // 5.5 Documents collaboratifs
  if (collabDocs.length > 0) {
    collabDocs.forEach((doc: any, idx: number) => {
      const suffix = idx > 0 ? `_${idx}` : '';
      const fileName = `${safeName(doc.title, 'document')}${suffix}.txt`;
      const content = `${doc.title}
Version: ${doc.version}
Date: ${doc.updatedAt}

---

${doc.content || '(Vide)'}`;
      zip.addFile(`${projectFolder}/documents_collaboratifs/${fileName}`, Buffer.from(content, 'utf-8'));
    });
  }

  // 5.6 Fichiers uploadés (téléchargement Cloudinary)
  if (files.length > 0) {
    for (const f of files) {
      try {
        const buffer = await readFileContent(f.filePath);

        if (buffer) {
          const safeFileName = safeName(f.fileName, `fichier_${f.id}`);
          zip.addFile(`${projectFolder}/fichiers/${safeFileName}`, buffer);
        } else {
          const meta = `Fichier indisponible : ${f.fileName}
Taille : ${f.fileSize} octets
Type : ${f.mimeType}
URL : ${f.filePath}`;
          zip.addFile(
            `${projectFolder}/fichiers/${safeName(f.fileName, 'fichier')}.meta.txt`,
            Buffer.from(meta, 'utf-8')
          );
        }
      } catch (err: any) {
        logger.warn(`⚠️ [export] Erreur fichier ${f.fileName}: ${err.message}`);
      }
    }
  }

  // 5.7 Entités extraites (JSON global)
  if (entities.length > 0) {
    zip.addFile(
      `${projectFolder}/analyse/entities.json`,
      Buffer.from(JSON.stringify(entities, null, 2), 'utf-8')
    );
  }

  // 5.8 Résumés IA (JSON global)
  if (summaries.length > 0) {
    zip.addFile(
      `${projectFolder}/analyse/summaries.json`,
      Buffer.from(JSON.stringify(summaries, null, 2), 'utf-8')
    );
  }

  // 5.9 Commentaires (JSON global)
  if (comments.length > 0) {
    zip.addFile(
      `${projectFolder}/analyse/comments.json`,
      Buffer.from(JSON.stringify(comments, null, 2), 'utf-8')
    );
  }

  const zipBuffer = zip.toBuffer();

  // 6. Audit log
  if (auditContext) {
    try {
      await logAudit({
        userId,
        userEmail: auditContext.userEmail,
        action: 'project_exported',
        targetType: 'project',
        targetId: projectId,
        targetName: project.title,
        status: 'success',
        metadata: {
          sizeBytes: zipBuffer.length,
          stats: metadata.stats,
          language: lang,
        },
        ip: auditContext.ip,
        userAgent: auditContext.userAgent,
      });
    } catch (err: any) {
      logger.warn(`⚠️ [export] Audit log échoué: ${err.message}`);
    }
  }

  logger.info(
    `📦 [export] Projet "${project.title}" exporté (${(zipBuffer.length / 1024).toFixed(1)} KB) par ${userId}`
  );

  return zipBuffer;
};
